"""The trust bridge (ADR-016): signatures over release facts, the drop-in
gate, the community index, the CLI, and the plugins API.

Every path is pinned: what loads and why, what is refused and why — the
refusals are the feature. The committed sample index entry is verified
against its committed artifact, so the curated index can never drift from
the bytes it vouches for.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from ledgerforge.__main__ import main as cli
from ledgerforge.plugins import PluginManager
from ledgerforge.plugins.trust import (
    TrustError,
    TrustStore,
    fingerprint,
    generate_publisher_keypair,
    sha256_hex,
    sign_artifact,
    static_manifest_facts_bytes,
    verify_signature,
)

REPO_ROOT = Path(__file__).resolve().parents[1]

PLUGIN_SOURCE = '''\
"""A test plugin (generated by tests/test_plugin_trust.py)."""
from ledgerforge.plugins import PluginManifest

PLUGIN = PluginManifest(name="{name}", version="{version}", api_compat="{api}")


def register(registry):
    registry.on("voucher.posted", lambda event: None)
'''

DYNAMIC_SOURCE = '''\
"""A plugin whose manifest is computed, not static."""
from ledgerforge.plugins import PluginManifest

_NAME = "dynamic" + "-pack"
PLUGIN = PluginManifest(name=_NAME, version="0.1.0", api_compat="0.2")


def register(registry):
    pass
'''


@pytest.fixture()
def publisher():
    """A fresh keypair + the sign helper, per test."""
    private_pem, public_b64 = generate_publisher_keypair()
    return private_pem, public_b64


def _write_plugin(
    directory: Path,
    module: str,
    *,
    name: str | None = None,
    version: str = "0.1.0",
    api: str = "0.2",
    source: str | None = None,
) -> Path:
    path = directory / f"{module}.py"
    path.write_text(
        source
        if source is not None
        else PLUGIN_SOURCE.format(name=name or module, version=version, api=api)
    )
    return path


def _sign_into(
    directory: Path,
    module: str,
    private_pem: str,
    *,
    name: str | None = None,
    version: str = "0.1.0",
    api: str = "0.2",
) -> dict:
    py_file = directory / f"{module}.py"
    doc = sign_artifact(
        private_pem,
        name=name or module,
        version=version,
        api_compat=api,
        artifact=py_file.read_bytes(),
    )
    (directory / f"{module}.py.sig").write_text(json.dumps(doc))
    return doc


# ------------------------------------------------------- signing primitives


def test_sign_verify_roundtrip(publisher):
    """keygen → sign → verify: the facts come back out of the mathematics."""
    private_pem, public_b64 = publisher
    artifact = PLUGIN_SOURCE.format(name="roundtrip", version="1.2.3", api="0.2").encode()
    doc = sign_artifact(
        private_pem, name="roundtrip", version="1.2.3", api_compat="0.2", artifact=artifact
    )
    assert doc["public_key"] == public_b64
    facts = verify_signature(doc, artifact)
    assert (facts.name, facts.version, facts.api_compat) == ("roundtrip", "1.2.3", "0.2")
    assert facts.sha256 == sha256_hex(artifact)


def test_tampered_artifact_refused(publisher):
    """One changed byte after signing: the digest mismatch refuses it."""
    _, _public = publisher
    artifact = b"# a plugin\n" + b"x" * 100
    doc = sign_artifact(
        publisher[0], name="t", version="0.1.0", api_compat="0.2", artifact=artifact
    )
    with pytest.raises(TrustError, match="changed after signing"):
        verify_signature(doc, artifact + b"!")


def test_signature_covers_facts_not_just_bytes(publisher):
    """Editing the facts in the document breaks the signature: a signature
    over bytes alone could be relabelled onto another release."""
    artifact = PLUGIN_SOURCE.format(name="real", version="1.0.0", api="0.2").encode()
    doc = sign_artifact(
        publisher[0], name="real", version="1.0.0", api_compat="0.2", artifact=artifact
    )
    relabelled = {**doc, "version": "9.9.9"}
    with pytest.raises(TrustError, match="does not verify"):
        verify_signature(relabelled, artifact)


def test_static_manifest_facts_and_the_dynamic_case(tmp_path):
    """Static extraction reads plain-string keyword manifests, and refuses
    to guess when the manifest is computed — that plugin needs an ack."""
    static = PLUGIN_SOURCE.format(name="s", version="1.0.0", api="0.3").encode()
    assert static_manifest_facts_bytes(static) == {
        "name": "s",
        "version": "1.0.0",
        "api_compat": "0.3",
    }
    assert static_manifest_facts_bytes(DYNAMIC_SOURCE.encode()) is None
    assert static_manifest_facts_bytes(b"not python {{{") is None


def test_fingerprint_is_stable_and_short():
    _, public_b64 = generate_publisher_keypair()
    assert fingerprint(public_b64) == fingerprint(public_b64)
    assert len(fingerprint(public_b64).split(":")) == 4


