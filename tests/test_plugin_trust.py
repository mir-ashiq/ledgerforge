def test_dynamic_manifest_loads_only_via_ack(tmp_path, publisher):
    """A computed manifest cannot be pinned by a signature (there are no
    static facts to check); the ack path still takes it — reviewed bytes,
    any manifest."""
    private_pem, public_b64 = publisher
    _write_plugin(tmp_path, "dynamic", name="dynamic-pack", source=DYNAMIC_SOURCE)
    _sign_into(tmp_path, "dynamic", private_pem, name="dynamic-pack")
    store = TrustStore.load(tmp_path)
    store.approve_publisher(public_b64)
    store.save()
    mgr = PluginManager()
    mgr.discover(extra_path=str(tmp_path))
    assert not any(r.manifest.name == "dynamic-pack" for r in mgr.plugins)
    assert "statically readable" in next(r for r in mgr.refusals if r.module == "dynamic").reason

    store.acknowledge("dynamic", sha256_hex((tmp_path / "dynamic.py").read_bytes()))
    store.save()
    mgr2 = PluginManager()
    mgr2.discover(extra_path=str(tmp_path))
    record = next(r for r in mgr2.plugins if r.manifest.name == "dynamic-pack")
    assert record.trust == "acknowledged"


