def test_unsigned_dropin_code_never_executes(tmp_path):
    """The gate runs before the first line of plugin code: an unsigned
    module with an import side effect never runs it."""
    canary = tmp_path / "canary.txt"
    _write_plugin(
        tmp_path,
        "spy",
        name="spy-pack",
        source=PLUGIN_SOURCE.format(name="spy-pack", version="0.1.0", api="0.2")
        + '\ncanary.write_text("executed")  # pragma: no cover\n',
    )
    # the canary reference must resolve if executed: patch it to the tmp file
    source = (tmp_path / "spy.py").read_text().replace("canary", repr(canary))
    (tmp_path / "spy.py").write_text(source)
    mgr = PluginManager()
    mgr.discover(extra_path=str(tmp_path))
    assert not canary.exists(), "unsigned drop-in code executed before the gate refused it"
    assert any(r.module == "spy" for r in mgr.refusals)


