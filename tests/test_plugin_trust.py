# ----------------------------------------------------------- the community index


def _mini_index(
    directory: Path,
    module: str,
    *,
    private_pem: str,
    public_b64: str,
    name: str,
    version: str = "0.1.0",
    api: str = "0.2",
    sha: str | None = None,
) -> Path:
    artifact = (directory / f"{module}.py").read_bytes()
    doc = sign_artifact(private_pem, name=name, version=version, api_compat=api, artifact=artifact)
    index = {
        "index_version": 1,
        "updated": "2026-11-07",
        "plugins": [
            {
                "name": name,
                "version": version,
                "api_compat": api,
                "summary": "test entry",
                "author": "tests",
                "homepage": "https://example",
                "artifact": f"{module}.py",
                "sha256": sha if sha is not None else doc["sha256"],
                "publisher_key": public_b64,
                "signature": doc["signature"],
            }
        ],
    }
    path = directory / "index.json"
    path.write_text(json.dumps(index))
    return path


