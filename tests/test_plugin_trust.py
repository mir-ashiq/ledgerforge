def test_cli_install_verifies_and_lands(tmp_path, publisher):
    """install = fetch → sha256 → signature → static facts → api floor →
    write plugin + .sig + approve publisher. The next boot loads it."""
    private_pem, public_b64 = publisher
    src_dir = tmp_path / "src"
    src_dir.mkdir()
    _write_plugin(src_dir, "demo_pack", name="demo-pack", version="3.1.4")
    index = _mini_index(
        src_dir,
        "demo_pack",
        private_pem=private_pem,
        public_b64=public_b64,
        name="demo-pack",
        version="3.1.4",
    )

    dropin = tmp_path / "dropins"
    assert (
        cli(["plugins", "install", "demo-pack", "--file", str(index), "--path", str(dropin)]) == 0
    )
    assert (dropin / "demo_pack.py").exists()
    assert (dropin / "demo_pack.py.sig").exists()
    store = TrustStore.load(dropin)
    assert store.is_approved(public_b64)

    mgr = PluginManager()
    mgr.discover(extra_path=str(dropin))
    record = next(r for r in mgr.plugins if r.manifest.name == "demo-pack")
    assert (record.source, record.trust, record.manifest.version) == ("drop-in", "signed", "3.1.4")
    assert not mgr.refusals


