#!/usr/bin/env python3
"""Regenerate the baseline Alembic revision (db/migrations/versions/0001_baseline.py)
from db/schema.sql + db/functions.sql.

Pre-1.0 policy (ADR-006): db/schema.sql stays the source of truth and is kept
idempotent; the baseline is re-embedded after schema changes. The drift test
in tests/test_migrations.py fails CI until this script is re-run.

Usage:  python scripts/regen_baseline.py [--check]
  --check: exit 1 if the committed baseline is stale (for CI/hooks).
"""

from __future__ import annotations

import datetime
import difflib
import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCES = (REPO_ROOT / "db" / "schema.sql", REPO_ROOT / "db" / "functions.sql")
TARGET = REPO_ROOT / "db" / "migrations" / "versions" / "0001_baseline.py"

REVISION = "0001_baseline"

HEADER = '''"""Baseline — the entire v0.x schema as one revision (ADR-006, issue #3).

Embeds db/schema.sql + db/functions.sql verbatim so `alembic upgrade head`
yields the same structure as the SQL bootstrap path. Regenerated by
scripts/regen_baseline.py; tests/test_migrations.py fails on drift.

Pre-1.0 policy: schema changes still land in the SQL files first, then this
baseline is regenerated (make baseline-regen). Post-1.0 this revision is
frozen and changes ship as new revisions that also update the SQL files.

Downgrade notes: pg_trgm is left in place (created IF NOT EXISTS, so it may
predate this migration and be shared); the ledgerforge_app role is dropped
best-effort for the same reason (shared clusters may retain it, revoked).

Revision ID: {revision}
Revises:
Create Date: {date}
"""

from alembic import op

revision = "{revision}"
down_revision = None
branch_labels = None
depends_on = None

# db/schema.sql — embedded verbatim by scripts/regen_baseline.py
SCHEMA_SQL = """\\
{schema_sql}"""

# db/functions.sql — embedded verbatim by scripts/regen_baseline.py
FUNCTIONS_SQL = """\\
{functions_sql}"""


def upgrade() -> None:
    op.execute(SCHEMA_SQL)
    op.execute(FUNCTIONS_SQL)
    # Alembic creates its bookkeeping table before this revision runs, so the
    # blanket GRANT ... ON ALL TABLES above caught it. The app role has no
    # business reading migration state, and the SQL bootstrap path never
    # grants it (its table is created after the files run) — revoke here to
    # keep both paths identical (tests/test_migrations.py).
    op.execute("REVOKE ALL ON alembic_version FROM ledgerforge_app")


def downgrade() -> None:
    """Drop every LedgerForge object the baseline created."""
    op.execute("DROP SCHEMA IF EXISTS rpt CASCADE")
    op.execute(
        """
        DROP TABLE IF EXISTS voucher_entries, vouchers, ledgers, groups,
            group_closure, voucher_types, doc_counters, audit_log, settings
        CASCADE
        """
    )
    # Trigger functions outlive their tables; drop them explicitly.
    op.execute(
        """
        DROP FUNCTION IF EXISTS
            trg_groups_after_insert(), trg_groups_before_update(),
            trg_groups_after_update(), trg_groups_before_delete(),
            trg_entries_check_date(), trg_entries_check_balance(),
            trg_audit_master(), trg_forbid_mutation()
        CASCADE
        """
    )
    # Revoke what survives the drops (e.g. alembic's own bookkeeping table)
    # so the role is left with nothing in this database.
    op.execute(
        """
        REVOKE ALL PRIVILEGES ON ALL TABLES IN SCHEMA public FROM ledgerforge_app;
        REVOKE ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public FROM ledgerforge_app;
        REVOKE ALL ON SCHEMA public FROM ledgerforge_app
        """
    )
    # Best-effort: the role may predate this migration or hold grants in
    # other databases of the cluster; keep it and say so if so.
    op.execute(
        """
        DO $$
        BEGIN
            DROP ROLE IF EXISTS ledgerforge_app;
        EXCEPTION WHEN dependent_objects_still_exist THEN
            RAISE NOTICE 'ledgerforge_app retained: still referenced elsewhere';
        END $$
        """
    )
'''


def build() -> str:
    schema_sql = SOURCES[0].read_text().rstrip("\n")
    functions_sql = SOURCES[1].read_text().rstrip("\n")
    if '"""' in schema_sql or '"""' in functions_sql:
        raise SystemExit("SQL sources contain triple double quotes; adjust embedding")
    date = datetime.datetime.now(datetime.UTC).date().isoformat()
    return HEADER.format(
        revision=REVISION, date=date, schema_sql=schema_sql, functions_sql=functions_sql
    )


def main() -> int:
    check = "--check" in sys.argv[1:]
    content = build()
    if check:
        current = TARGET.read_text()
        # The Create Date line legitimately differs between runs; compare the rest.
        normalize = lambda text: "\n".join(  # noqa: E731
            line for line in text.splitlines() if not line.startswith("Create Date:")
        )
        if normalize(current) == normalize(content):
            print("baseline is up to date")
            return 0
        diff = "\n".join(
            difflib.unified_diff(
                normalize(current).splitlines(),
                normalize(content).splitlines(),
                "committed",
                "regenerated",
                lineterm="",
            )
        )
        print(f"baseline is STALE — run scripts/regen_baseline.py\n\n{diff}", file=sys.stderr)
        return 1
    TARGET.write_text(content)
    print(f"wrote {TARGET.relative_to(REPO_ROOT)} ({len(content.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
